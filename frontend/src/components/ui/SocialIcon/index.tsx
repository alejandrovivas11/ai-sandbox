// ─── Renderer ─────────────────────────────────────────────────────────────────

function SocialIcon({ name, variant = 'original', size = 24, className }: SocialIconProps) {
  const color = variant === 'original' ? BRAND_COLORS[name] : 'currentColor'
  const fillColor = Array.isArray(color) ? color[0] : color
  const def = ICONS[name]

  const commonProps = {
    width: size,
    height: size,
    viewBox: '0 0 24 24',
    fill: fillColor,
    'aria-label': name,
    role: 'img' as const,
    className: cn('shrink-0', variant === 'neutral' && 'text-current', className),
  }

  if (!def) return null

  if (def.type === 'multi') {
    return (
      <svg {...commonProps}>
        {def.shapes.map((shape, i) => (
          <path
            key={i}
            d={shape.d}
            fill={shape.fill ?? fillColor}
            opacity={shape.opacity}
          />
        ))}
      </svg>
    )
  }

  if (def.type === 'circle') {
    return (
      <svg {...commonProps}>
        <circle cx={def.cx} cy={def.cy} r={def.r} fill={fillColor} />
      </svg>
    )
  }

  return (
    <svg {...commonProps} fillRule={def.fillRule}>
      <path d={def.d} />
    </svg>
  )
}

